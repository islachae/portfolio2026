// Pebbo's rules live in one place, content/cases/pebbo-brain.ts (PEBBO_RULES). The live endpoint
// (api/pebbo.js) needs the same text but isn't part of the Next build, so `npm run build` copies it
// into api/_pebbo-rules.js first (files starting with _ in api/ aren't endpoints). Commit the result.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const src = readFileSync(new URL("../content/cases/pebbo-brain.ts", import.meta.url), "utf8");
const m = src.match(/export const PEBBO_RULES = `([\s\S]*?)`;/);
if (!m) throw new Error("PEBBO_RULES not found in content/cases/pebbo-brain.ts");
const out = new URL("../api/_pebbo-rules.js", import.meta.url);
const js = `// Generated by scripts/sync-pebbo-rules.mjs from PEBBO_RULES in content/cases/pebbo-brain.ts. Don't edit.\nexport const RULES = ${JSON.stringify(m[1])};\n`;
if (!existsSync(out) || readFileSync(out, "utf8") !== js) {
  writeFileSync(out, js);
  console.log("pebbo rules: api/_pebbo-rules.js updated");
} else {
  console.log("pebbo rules: in sync");
}
